import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const SUPA = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'supabase');
const order = [
  'add-istqb-course.sql', 'seed-istqb-modules.sql',
  ...Array.from({ length: 12 }, (_, i) => `seed-istqb-module-${i + 1}-lessons.sql`),
  ...Array.from({ length: 12 }, (_, i) => `seed-istqb-module-${i + 1}-enhancements.sql`),
];
let out = `-- ============================================================================
-- ISTQB Foundation Masterclass — COMBINED SEED (course + 14 modules + 72 lessons + enhancements)
-- Generated by scripts/content/build-istqb-combined.mjs. Run ONCE in the Supabase SQL editor.
-- Prereq: lessons-schema.sql + lesson-enhancements-schema.sql already applied (they are, in prod).
-- Idempotent. (Practice questions, mock exams and resources are seeded separately.)
-- ============================================================================\n\nbegin;\n`;
for (const f of order) { out += `\n-- >>> ${f}\n` + readFileSync(join(SUPA, f), 'utf8').trimEnd() + '\n'; }
out += `\ncommit;\n`;
writeFileSync(join(SUPA, 'seed-istqb-ALL.sql'), out);
console.log('Wrote supabase/seed-istqb-ALL.sql');
