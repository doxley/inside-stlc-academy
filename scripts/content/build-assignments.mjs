// Generates supabase/seed-modern-automation-assignments.sql from a single
// structured content file, so the SQL is always valid (no hand-escaping).
// The content file default-exports:
//   { courseSlug, assignments: [{ moduleNumber, title, submissionType,
//     instructions, templateSlug?, briefSlug? }] }
// instructions may use the lightweight markdown the app renders (## / - / code).
//
// Usage: node scripts/content/build-assignments.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');

const data = (await import('./modern-automation-assignments.mjs')).default;
const { courseSlug, assignments } = data;

const L = '$A$'; // dollar-quote delimiter for text columns
const txt = (s) => {
  const v = s == null ? '' : String(s);
  if (v.includes(L)) throw new Error(`Delimiter ${L} clash in an assignment`);
  return `${L}${v}${L}`;
};
const nullable = (s) => (s == null ? 'null' : txt(s));

let sql = `-- ============================================================
-- Modern Test Automation Bootcamp — assignments (12 hands-on labs + 3 projects).
-- Generated by scripts/content/build-assignments.mjs — do not hand-edit;
-- edit scripts/content/modern-automation-assignments.mjs and regenerate.
-- Run AFTER add-modern-automation-course.sql and seed-modern-automation-modules.sql.
-- Idempotent: inserts an assignment only if the module has none, then wires
-- optional template/brief slugs. Tutor model answers live in
-- docs/MODERN_AUTOMATION_TUTOR_ANSWER_KEY.md.
-- ============================================================

alter table public.assignments add column if not exists template_slug text;
alter table public.assignments add column if not exists brief_slug text;

insert into public.assignments (module_id, title, instructions, required, submission_type)
select m.id, v.title, v.instructions, true, v.submission_type
from public.modules m
join public.courses c on c.id = m.course_id
cross join (values
`;

sql += assignments
  .map((a) => `  (${a.moduleNumber}, ${txt(a.title)}, ${txt(a.instructions)}, ${txt(a.submissionType)})`)
  .join(',\n');

sql += `
) as v(module_number, title, instructions, submission_type)
where c.slug = '${courseSlug}'
  and m.module_number = v.module_number
  and not exists (select 1 from public.assignments a where a.module_id = m.id);
`;

// Optional slug wiring (only rows that declare one).
const withSlugs = assignments.filter((a) => a.templateSlug || a.briefSlug);
if (withSlugs.length) {
  sql += `
update public.assignments a set template_slug = v.template_slug, brief_slug = v.brief_slug
from (values
${withSlugs.map((a) => `  (${a.moduleNumber}, ${nullable(a.templateSlug)}, ${nullable(a.briefSlug)})`).join(',\n')}
) as v(module_number, template_slug, brief_slug)
join public.modules m on m.module_number = v.module_number
join public.courses c on c.id = m.course_id
where a.module_id = m.id and c.slug = '${courseSlug}';
`;
}

writeFileSync(join(ROOT, 'supabase', 'seed-modern-automation-assignments.sql'), sql);
console.log(`wrote ${assignments.length} assignments`);
