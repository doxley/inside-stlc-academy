// Concatenates all API Testing Masterclass seed files into ONE runnable file,
// in dependency order, wrapped in a transaction. Regenerate after editing content:
//   node scripts/content/build-combined.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const SUPA = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'supabase');

const order = [
  'add-api-testing-course.sql',
  'seed-api-testing-modules.sql',
  ...Array.from({ length: 10 }, (_, i) => `seed-api-testing-module-${i + 1}-lessons.sql`),
  ...Array.from({ length: 10 }, (_, i) => `seed-api-module${i + 1}-enhancements.sql`),
];

let out = `-- ============================================================================
-- API Testing Masterclass — COMBINED SEED (course + 10 modules + 55 lessons + enhancements)
-- Generated by scripts/content/build-combined.mjs — do not hand-edit.
-- Run ONCE in the Supabase SQL editor. Prerequisite: lessons-schema.sql and
-- lesson-enhancements-schema.sql already applied (they are, in prod). Idempotent.
-- ============================================================================

begin;

`;
for (const f of order) {
  out += `\n-- >>> ${f} ${'>'.repeat(Math.max(0, 60 - f.length))}\n`;
  out += readFileSync(join(SUPA, f), 'utf8').trimEnd() + '\n';
}
out += `\ncommit;\n\n-- Verify: select count(*) from public.lessons l join public.modules m on m.id=l.module_id join public.courses c on c.id=m.course_id where c.slug='api-testing-masterclass'; -- expect 55\n`;

writeFileSync(join(SUPA, 'seed-api-testing-ALL.sql'), out);
console.log('Wrote supabase/seed-api-testing-ALL.sql');
