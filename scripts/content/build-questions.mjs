// Builds supabase/seed-istqb-questions.sql from the structured question files in
// scripts/content/istqb-questions/module{1..12}.mjs. Also composes TWO 40-question
// mock exams (exam-weighted, drawn from the topic bank). Idempotent: rows upsert on
// (course_id, ext_key), so re-running updates in place without wiping question_attempts.
//
// Usage: node scripts/content/build-questions.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');
const SLUG = 'istqb-foundation-masterclass';

const L = '$L$';  // dollar-quote for text
const J = '$J$';  // dollar-quote for jsonb
const txt = (s, ctx) => {
  const v = s == null ? '' : String(s);
  if (v.includes(L)) throw new Error(`Delimiter ${L} clash at ${ctx}`);
  return `${L}${v}${L}`;
};
const jsonb = (obj, ctx) => {
  const v = JSON.stringify(obj);
  if (v.includes(J)) throw new Error(`Delimiter ${J} clash at ${ctx}`);
  return `${J}${v}${J}::jsonb`;
};

// ── Load all module files ─────────────────────────────────────────
const modules = [];
for (let n = 1; n <= 12; n++) {
  const mod = (await import(`./istqb-questions/module${n}.mjs`)).default;
  if (mod.moduleNumber !== n) throw new Error(`module${n}.mjs has moduleNumber ${mod.moduleNumber}`);
  // structural validation
  mod.questions.forEach((q, i) => {
    const ctx = `m${n} q${i + 1}`;
    // Agents used slightly different field names; normalise to questionText.
    q.questionText = q.questionText ?? q.question ?? q.prompt ?? q.stem;
    if (!q.questionText) throw new Error(`${ctx}: missing question text`);
    if (!Array.isArray(q.options) || q.options.length !== 4) throw new Error(`${ctx}: needs exactly 4 options`);
    const correct = q.options.filter((o) => o.correct === true);
    if (correct.length !== 1) throw new Error(`${ctx}: needs exactly 1 correct option (has ${correct.length})`);
    q.options.forEach((o, oi) => {
      if (!o.text) throw new Error(`${ctx} opt${oi + 1}: missing text`);
      if (typeof o.why !== 'string' || !o.why) throw new Error(`${ctx} opt${oi + 1}: missing why`);
    });
    if (!q.explanation) throw new Error(`${ctx}: missing explanation`);
    if (q.kLevel && !['K1', 'K2', 'K3'].includes(q.kLevel)) throw new Error(`${ctx}: bad kLevel ${q.kLevel}`);
  });
  modules.push(mod);
}

const totalBank = modules.reduce((s, m) => s + m.questions.length, 0);

// ── Emit an insert row ────────────────────────────────────────────
function row(extKey, topic, moduleNumber, kLevel, mock, mockOrder, q) {
  const ctx = extKey;
  return `insert into public.practice_questions
  (course_id, ext_key, syllabus_topic, module_number, k_level, mock, mock_order, question_text, options, explanation, workplace_example)
select c.id, ${txt(extKey, ctx)}, ${txt(topic, ctx)}, ${moduleNumber}, ${kLevel ? txt(kLevel, ctx) : 'null'}, ${mock ?? 'null'}, ${mockOrder ?? 'null'}, ${txt(q.questionText, ctx)}, ${jsonb(q.options, ctx)}, ${txt(q.explanation, ctx)}, ${txt(q.workplaceExample, ctx)}
from public.courses c where c.slug = '${SLUG}'
on conflict (course_id, ext_key) do update set
  syllabus_topic = excluded.syllabus_topic, module_number = excluded.module_number, k_level = excluded.k_level,
  mock = excluded.mock, mock_order = excluded.mock_order, question_text = excluded.question_text,
  options = excluded.options, explanation = excluded.explanation, workplace_example = excluded.workplace_example;`;
}

let sql = `-- ============================================================
-- ISTQB Foundation Masterclass — practice question bank + 2 mock exams.
-- Generated by scripts/content/build-questions.mjs — do not hand-edit.
-- Run AFTER istqb-exam-schema.sql and after the course row exists.
-- Idempotent (upsert on (course_id, ext_key)).
-- Bank: ${totalBank} questions across ${modules.length} topics; Mocks: 2 x 40.
-- ============================================================

begin;

`;

// ── Topic bank rows ───────────────────────────────────────────────
for (const m of modules) {
  sql += `-- Module ${m.moduleNumber}: ${m.syllabusTopic} (${m.questions.length})\n`;
  m.questions.forEach((q, i) => {
    const extKey = `m${m.moduleNumber}-${String(i + 1).padStart(2, '0')}`;
    sql += row(extKey, m.syllabusTopic, m.moduleNumber, q.kLevel, null, null, q) + '\n\n';
  });
}

// ── Compose 2 mock exams (exam-weighted, 40 each) ─────────────────
// Weighting by source module, summing to 40, mirroring the CTFL v4.0 blueprint.
const MOCK_WEIGHTS = { 1: 6, 2: 5, 3: 4, 4: 11, 5: 4, 6: 2, 7: 3, 8: 2, 9: 2, 10: 1 };
const byModule = new Map(modules.map((m) => [m.moduleNumber, m]));

function buildMock(mockNo, offset) {
  // Deterministically pick `weight` questions per module, starting at `offset`
  // (wrapping), so Mock 2 draws a largely different slice than Mock 1.
  const picked = [];
  for (const [modNo, weight] of Object.entries(MOCK_WEIGHTS)) {
    const m = byModule.get(Number(modNo));
    const qs = m.questions;
    for (let k = 0; k < weight; k++) {
      const idx = (offset + k) % qs.length;
      picked.push({ m, q: qs[idx], srcIdx: idx });
    }
  }
  let out = `-- Mock Exam ${mockNo} (${picked.length} questions, exam-weighted)\n`;
  picked.forEach((p, i) => {
    const extKey = `mock${mockNo}-${String(i + 1).padStart(2, '0')}`;
    out += row(extKey, p.m.syllabusTopic, p.m.moduleNumber, p.q.kLevel, mockNo, i + 1, p.q) + '\n\n';
  });
  return { out, count: picked.length };
}

const mock1 = buildMock(1, 0);
const mock2 = buildMock(2, 3); // offset so it overlaps Mock 1 minimally
sql += mock1.out + mock2.out;

sql += 'commit;\n';

writeFileSync(join(ROOT, 'supabase', 'seed-istqb-questions.sql'), sql);
console.log(`Wrote seed-istqb-questions.sql`);
console.log(`  Topic bank: ${totalBank} questions across ${modules.length} topics`);
console.log(`  Mock 1: ${mock1.count} questions | Mock 2: ${mock2.count} questions`);
console.log(`  Total rows: ${totalBank + mock1.count + mock2.count}`);
